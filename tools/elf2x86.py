#!/usr/bin/env python3
"""elf2x86.py — turn an ARM ELF object of game *data* into i686 GAS assembly.

pret's data files (event scripts, battle scripts, map tables, sound data) are
written for the ARM assembler and lean heavily on its macros. Instead of
rewriting that assembly for x86, we assemble it with the real ARM assembler and
translate the resulting object: every byte is kept as is, every symbol keeps
its exact offset, and every absolute address (R_ARM_ABS32) becomes a
`.long symbol+addend` that the x86 linker resolves. The output is therefore
byte-for-byte the data the GBA build would contain, with pointers re-targeted
to the PC build's addresses.

usage: elf2x86.py in.o out.s
"""
import sys
from collections import defaultdict

from elftools.elf.elffile import ELFFile
from elftools.elf.relocation import RelocationSection

R_ARM_NONE, R_ARM_ABS32 = 0, 2


def c_name(name):
    """i686 MinGW mangles C symbols with a leading underscore."""
    return "_" + name


def main(src, dst):
    with open(src, "rb") as f:
        elf = ELFFile(f)
        symtab = elf.get_section_by_name(".symtab")
        syms = list(symtab.iter_symbols())
        sections = list(elf.iter_sections())

        # labels to emit at each (section index, offset)
        labels = defaultdict(list)
        local_names = {}
        for i, s in enumerate(syms):
            shndx = s["st_shndx"]
            if not isinstance(shndx, int) or s.name == "" or s["st_info"]["type"] in ("STT_SECTION", "STT_FILE"):
                continue
            if s.name.startswith("$"):  # ARM mapping symbols ($d, $a, $t)
                continue
            if s["st_info"]["bind"] == "STB_LOCAL":
                local_names[i] = f"L{abs(hash(src)) % 100000}_{i}"
                labels[(shndx, s["st_value"])].append((local_names[i], False))
            else:
                labels[(shndx, s["st_value"])].append((c_name(s.name), True))

        def target(sym_index, addend):
            s = syms[sym_index]
            kind = s["st_info"]["type"]
            if kind == "STT_SECTION":
                base = f"Lsec_{s['st_shndx']}"
            elif sym_index in local_names:
                base = local_names[sym_index]
            else:
                base = c_name(s.name)
            return f"{base}{addend:+d}" if addend else base

        relocs = defaultdict(dict)  # section index -> offset -> expression
        for sec in sections:
            if not isinstance(sec, RelocationSection):
                continue
            tgt_index = sec["sh_info"]
            data = sections[tgt_index].data()
            for r in sec.iter_relocations():
                t = r["r_info_type"]
                if t == R_ARM_NONE:
                    continue
                if t != R_ARM_ABS32:
                    sys.exit(f"{src}: unsupported relocation type {t} at {sections[tgt_index].name}+{r['r_offset']:#x}")
                off = r["r_offset"]
                addend = int.from_bytes(data[off:off + 4], "little", signed=True)
                relocs[tgt_index][off] = target(r["r_info_sym"], addend)

        out = [f"# generated by elf2x86.py from {src} — do not edit"]
        for idx, sec in enumerate(sections):
            if sec["sh_type"] not in ("SHT_PROGBITS", "SHT_NOBITS") or sec["sh_size"] == 0:
                continue
            if not sec["sh_flags"] & 2:  # SHF_ALLOC
                continue
            nobits = sec["sh_type"] == "SHT_NOBITS"
            writable = sec["sh_flags"] & 1
            if nobits:
                out.append("\t.bss")
            elif writable:
                out.append("\t.data")
            else:
                out.append('\t.section .rdata,"dr"')
            align = max(1, sec["sh_addralign"])
            out.append(f"\t.balign {align}")
            out.append(f"Lsec_{idx}:")
            size = sec["sh_size"]
            data = b"" if nobits else sec.data()
            rel = relocs.get(idx, {})
            pending = []

            def flush():
                if pending:
                    out.append("\t.byte " + ",".join(str(b) for b in pending))
                    pending.clear()

            off = 0
            while off < size:
                for name, is_global in labels.get((idx, off), []):
                    flush()
                    if is_global:
                        out.append(f"\t.globl {name}")
                    out.append(f"{name}:")
                if off in rel:
                    flush()
                    out.append(f"\t.long {rel[off]}")
                    off += 4
                    continue
                if nobits:
                    # find the next label to keep .space runs short
                    nxt = min([o for (s, o) in labels if s == idx and o > off] + [size])
                    out.append(f"\t.space {nxt - off}")
                    off = nxt
                    continue
                pending.append(data[off])
                if len(pending) == 32:
                    flush()
                off += 1
            flush()
            for name, is_global in labels.get((idx, size), []):
                if is_global:
                    out.append(f"\t.globl {name}")
                out.append(f"{name}:")

    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
